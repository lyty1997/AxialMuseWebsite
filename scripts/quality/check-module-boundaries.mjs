function toPosix(path) {
  return path.split(sep).join("/");
}

function sourcePath(root, path) {
  return toPosix(relative(root, path));
}

function addIssue(issues, code, path, message) {
  issues.push({code, sourcePath: path, message});
}

function sortIssues(issues) {
  return issues.sort((left, right) => (
    left.sourcePath.localeCompare(right.sourcePath, "en")
    || left.code.localeCompare(right.code, "en")
    || left.message.localeCompare(right.message, "zh-CN")
  ));
}

function readJsonFile(root, relativePath, issues) {
  const path = resolve(root, relativePath);
  try {
    const metadata = lstatSync(path);
    if (metadata.isSymbolicLink() || !metadata.isFile()) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_CONFIG_FILE",
        relativePath,
        "配置必须是仓库内普通文件且不能是符号链接。",
      );
      return null;
    }
    const value = JSON.parse(readFileSync(path, "utf8"));
    if (value === null || typeof value !== "object" || Array.isArray(value)) {
      throw new TypeError("root must be object");
    }
    return value;
  } catch {
    addIssue(
      issues,
      "MODULE_BOUNDARY_CONFIG_JSON",
      relativePath,
      "配置不是合法 JSON object。",
    );
    return null;
  }
}

function hasExactKeys(value, expected) {
  return Object.keys(value).sort().join("\n") === [...expected].sort().join("\n");
}

function hasExactJsonValue(actual, expected) {
  return JSON.stringify(actual) === JSON.stringify(expected);
}

function validateRootContracts(root, issues) {
  try {
    const configSource = readFileSync(resolve(root, "docusaurus.config.ts"), "utf8");
    const previewModeBindings = configSource.match(
      /(?:^|\n)const isPreview = buildContext\.mode === "preview";(?:\n|$)/gu,
    ) ?? [];
    const rootIndexingBindings = configSource.match(
      /(?:^|\n)  noIndex: isPreview,(?:\n|$)/gu,
    ) ?? [];
    const sitemapBindings = configSource.match(
      /(?:^|\n)        sitemap: isPreview \? false : \{\},(?:\n|$)/gu,
    ) ?? [];
    const debugBindings = configSource.match(
      /(?:^|\n)        debug: false,(?:\n|$)/gu,
    ) ?? [];
    const allRootIndexingDeclarations = configSource.match(/\bnoIndex\s*:/gu) ?? [];
    const allSitemapDeclarations = configSource.match(/\bsitemap\s*:/gu) ?? [];
    const allDebugDeclarations = configSource.match(/\bdebug\s*:/gu) ?? [];
    const unsupportedGeneratedDirectoryDeclarations = configSource.match(
      /\bgeneratedFilesDir\s*:/gu,
    ) ?? [];
    if (
      previewModeBindings.length !== 1
      || rootIndexingBindings.length !== 1
      || sitemapBindings.length !== 1
      || debugBindings.length !== 1
      || allRootIndexingDeclarations.length !== 1
      || allSitemapDeclarations.length !== 1
      || allDebugDeclarations.length !== 1
      || unsupportedGeneratedDirectoryDeclarations.length !== 0
    ) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_INDEXING_CONTRACT",
        "docusaurus.config.ts",
        "根配置必须由唯一 preview 判据同时绑定 production 可索引、preview noindex、禁 sitemap 与禁 debug 路由，且不得声明框架不支持的 generatedFilesDir。",
      );
    }
  } catch {
    addIssue(
      issues,
      "MODULE_BOUNDARY_INDEXING_CONTRACT",
      "docusaurus.config.ts",
      "根 indexing 契约无法读取。",
    );
  }
  try {
    if (readFileSync(resolve(root, "sidebars.ts"), "utf8") !== EXPECTED_SIDEBARS_SOURCE) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_SIDEBARS_CONTRACT",
        "sidebars.ts",
        "根侧栏必须精确只声明 projects/writing 两个 autogenerated slice。",
      );
    }
  } catch {
    addIssue(
      issues,
      "MODULE_BOUNDARY_SIDEBARS_CONTRACT",
      "sidebars.ts",
      "根侧栏契约无法读取。",
    );
  }
  const tsconfig = readJsonFile(root, "tsconfig.json", issues);
  if (tsconfig !== null) {
    if (!hasExactKeys(tsconfig, ["extends", "compilerOptions", "include"])) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TSCONFIG_ROOT",
        "tsconfig.json",
        "根 tsconfig 只能声明 extends、compilerOptions 与 include。",
      );
    }
    if (tsconfig.extends !== EXPECTED_TSCONFIG.extends) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TSCONFIG_EXTENDS",
        "tsconfig.json",
        "根 tsconfig 必须继承精确官方 Docusaurus 基线。",
      );
    }
    const compilerOptions = tsconfig.compilerOptions;
    if (
      compilerOptions === null
      || typeof compilerOptions !== "object"
      || Array.isArray(compilerOptions)
      || !hasExactKeys(compilerOptions, Object.keys(EXPECTED_TSCONFIG.compilerOptions))
      || Object.entries(EXPECTED_TSCONFIG.compilerOptions)
        .some(([key, value]) => compilerOptions[key] !== value)
    ) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TSCONFIG_OPTIONS",
        "tsconfig.json",
        "compilerOptions 必须精确等于 D-076 的四项显式收紧配置。",
      );
    }
    if (
      !Array.isArray(tsconfig.include)
      || tsconfig.include.length !== EXPECTED_TSCONFIG.include.length
      || tsconfig.include.some((value, index) => value !== EXPECTED_TSCONFIG.include[index])
    ) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TSCONFIG_INCLUDE",
        "tsconfig.json",
        "生产 TypeScript program 的 include 集合或顺序发生漂移。",
      );
    }
  }

  const testTsconfig = readJsonFile(root, "tests/tsconfig.json", issues);
  if (testTsconfig !== null) {
    if (!hasExactKeys(testTsconfig, ["extends", "compilerOptions", "include"])) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TEST_TSCONFIG_ROOT",
        "tests/tsconfig.json",
        "测试 tsconfig 只能声明 extends、compilerOptions 与 include。",
      );
    }
    if (testTsconfig.extends !== EXPECTED_TEST_TSCONFIG.extends) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TEST_TSCONFIG_EXTENDS",
        "tests/tsconfig.json",
        "测试 tsconfig 必须只继承根生产配置。",
      );
    }
    const compilerOptions = testTsconfig.compilerOptions;
    if (
      compilerOptions === null
      || typeof compilerOptions !== "object"
      || Array.isArray(compilerOptions)
      || !hasExactKeys(compilerOptions, Object.keys(EXPECTED_TEST_TSCONFIG.compilerOptions))
      || Object.entries(EXPECTED_TEST_TSCONFIG.compilerOptions)
        .some(([key, value]) => !hasExactJsonValue(compilerOptions[key], value))
    ) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TEST_TSCONFIG_OPTIONS",
        "tests/tsconfig.json",
        "测试 compilerOptions 必须精确等于 E-012 NodeNext/ES2024 emit 契约。",
      );
    }
    if (!hasExactJsonValue(testTsconfig.include, EXPECTED_TEST_TSCONFIG.include)) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TEST_TSCONFIG_INCLUDE",
        "tests/tsconfig.json",
        "测试 TypeScript program 的 include 集合或顺序发生漂移。",
      );
    }
  }

  for (const relativePath of ["src/package.json", "tests/package.json"]) {
    const packageBoundary = readJsonFile(root, relativePath, issues);
    if (
      packageBoundary !== null
      && (
        !hasExactKeys(packageBoundary, Object.keys(EXPECTED_SOURCE_PACKAGE))
        || Object.entries(EXPECTED_SOURCE_PACKAGE)
          .some(([key, value]) => packageBoundary[key] !== value)
      )
    ) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_SOURCE_PACKAGE",
        relativePath,
        "局部源码 package 必须精确只声明 type=module 与 private=true。",
      );
    }
  }

  const packageJson = readJsonFile(root, "package.json", issues);
  if (packageJson !== null) {
    if (Object.hasOwn(packageJson, "type")) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_PACKAGE_TYPE",
        "package.json",
        "根 package.json 不得改变 Docusaurus 生成 .js 文件的 CommonJS 解释边界。",
      );
    }
    for (const scriptName of [
      "typecheck",
      "test",
      "build",
      "package:artifact",
      "check:artifact",
    ]) {
      const allowed = RUN_SCRIPT_COMMANDS[scriptName];
      if (!allowed.includes(packageJson.scripts?.[scriptName])) {
        addIssue(
          issues,
          "MODULE_BOUNDARY_SCRIPT_CONTRACT",
          "package.json",
          `${scriptName} 没有消费 E-010 的精确受控命令。`,
        );
      }
    }
  }

  try {
    const manifest = readAndValidateManifest(root);
    readAndValidateRuntimeContract({root, manifest});
  } catch (error) {
    const upstreamCode = typeof error?.code === "string" ? error.code : "UNKNOWN";
    addIssue(
      issues,
      "MODULE_BOUNDARY_RUNTIME_CONTRACT",
      ".nvmrc",
      `Node 版本契约未通过既有 E-010 校验（${upstreamCode}）。`,
    );
  }
}

function collectTargetFiles(root, issues) {
  const files = [];
  for (const relativePath of ROOT_TYPESCRIPT_FILES) {
    const path = resolve(root, relativePath);
    try {
      const metadata = lstatSync(path);
      if (metadata.isSymbolicLink() || !metadata.isFile()) {
        throw new TypeError("not a regular file");
      }
      files.push(path);
    } catch {
      addIssue(
        issues,
        "MODULE_BOUNDARY_FRAMEWORK_ENTRY",
        relativePath,
        "Docusaurus 框架入口必须是普通 TypeScript 文件。",
      );
    }
  }
  for (const relativePath of FORBIDDEN_ROOT_JAVASCRIPT) {
    if (existsSync(resolve(root, relativePath))) {
      addIssue(
        issues,
        "MODULE_BOUNDARY_SOURCE_EXTENSION",
        relativePath,
        "Docusaurus 目标入口不得使用 JavaScript/JSX。",
      );
    }
  }

  const srcRoot = resolve(root, "src");
  if (!existsSync(srcRoot)) {
    addIssue(
      issues,
      "MODULE_BOUNDARY_SOURCE_ROOT",
      "src",
      "Docusaurus 标准 src 物理根缺失。",
    );
    return files.sort();
  }

  const walk = (directory) => {
    for (const entry of readdirSync(directory, {withFileTypes: true})) {
      const path = resolve(directory, entry.name);
      const relativePath = sourcePath(root, path);
      if (entry.isSymbolicLink()) {
        addIssue(
          issues,
          "MODULE_BOUNDARY_SOURCE_LINK",
          relativePath,
          "目标源码树不得包含符号链接。",
        );
        continue;
      }
      if (entry.isDirectory()) {
        walk(path);
        continue;
      }
      if (!entry.isFile()) continue;
      const extension = extname(entry.name);
      if (JAVASCRIPT_EXTENSIONS.has(extension)) {
        addIssue(
          issues,
          "MODULE_BOUNDARY_SOURCE_EXTENSION",
          relativePath,
          "Docusaurus 目标源码不得使用 JavaScript/JSX。",
        );
        continue;
      }
      if (!TYPESCRIPT_EXTENSIONS.has(extension)) continue;
      const rootName = relativePath.split("/")[1];
      if (!SOURCE_ROOTS.has(rootName)) {
        addIssue(
          issues,
          "MODULE_BOUNDARY_SOURCE_LAYER",
          relativePath,
          "TypeScript 源码不属于 D-075 的任一物理层。",
        );
        continue;
      }
      files.push(path);
    }
  };
  walk(srcRoot);

  const walkTests = (directory) => {
    for (const entry of readdirSync(directory, {withFileTypes: true})) {
      const path = resolve(directory, entry.name);
      const relativePath = sourcePath(root, path);
      if (entry.isSymbolicLink()) {
        addIssue(
          issues,
          "MODULE_BOUNDARY_TEST_SOURCE_LINK",
          relativePath,
          "测试源码树不得包含符号链接。",
        );
        continue;
      }
      if (entry.isDirectory()) {
        walkTests(path);
        continue;
      }
      if (!entry.isFile()) continue;
      if (/\.test\.(?:js|jsx|tsx)$/u.test(entry.name)) {
        addIssue(
          issues,
          "MODULE_BOUNDARY_TEST_SOURCE_EXTENSION",
          relativePath,
          "领域与构建测试必须使用 .test.ts。",
        );
        continue;
      }
      if (entry.name.endsWith(".ts")) files.push(path);
    }
  };
  for (const relativeRoot of TEST_SOURCE_ROOTS) {
    const testRoot = resolve(root, relativeRoot);
    try {
      const metadata = lstatSync(testRoot);
      if (metadata.isSymbolicLink() || !metadata.isDirectory()) {
        throw new TypeError("not a regular directory");
      }
      walkTests(testRoot);
    } catch {
      addIssue(
        issues,
        "MODULE_BOUNDARY_TEST_SOURCE_ROOT",
        relativeRoot,
        "E-012 测试物理层必须是仓库内普通目录。",
      );
    }
  }
  return files.sort();
}

function decodeStringLiteral(raw) {
  const quote = raw[0];
  let result = "";
  for (let index = 1; index < raw.length - 1; index += 1) {
    const character = raw[index];
    if (character !== "\\") {
      result += character;
      continue;
    }
    index += 1;
    const escaped = raw[index];
    if (escaped === "\n" || escaped === "\u2028" || escaped === "\u2029") {
      continue;
    }
    if (escaped === "\r") {
      if (raw[index + 1] === "\n") index += 1;
      continue;
    }
    const simple = {
      "'": "'",
      "\"": "\"",
      "\\": "\\",
      b: "\b",
      f: "\f",
      n: "\n",
      r: "\r",
      t: "\t",
      v: "\v",
      0: "\0",
    };
    if (Object.hasOwn(simple, escaped)) {
      result += simple[escaped];
      continue;
    }
    if (escaped === "x") {
      const digits = raw.slice(index + 1, index + 3);
      if (!/^[0-9a-fA-F]{2}$/u.test(digits)) throw new SyntaxError("bad hex escape");
      result += String.fromCodePoint(Number.parseInt(digits, 16));
      index += 2;
      continue;
    }
    if (escaped === "u") {
      if (raw[index + 1] === "{") {
        const end = raw.indexOf("}", index + 2);
        const digits = raw.slice(index + 2, end);
        if (end === -1 || !/^[0-9a-fA-F]{1,6}$/u.test(digits)) {
          throw new SyntaxError("bad unicode escape");
        }
        result += String.fromCodePoint(Number.parseInt(digits, 16));
        index = end;
        continue;
      }
      const digits = raw.slice(index + 1, index + 5);
      if (!/^[0-9a-fA-F]{4}$/u.test(digits)) throw new SyntaxError("bad unicode escape");
      result += String.fromCodePoint(Number.parseInt(digits, 16));
      index += 4;
      continue;
    }
    throw new SyntaxError(`unsupported escape in ${quote} string`);
  }
  return result;
}

