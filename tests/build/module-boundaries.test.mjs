test("D-075 本地 preset 默认导出只允许精确入口路径", () => {
  withFixture((root) => {
    writeFixture(
      root,
      "src/build/content/docusaurus-preset-copy.ts",
      "export default function copiedPreset() { return {}; }\n",
    );
    const issues = checkModuleBoundaries({root}).issues;
    assert.ok(issues.some((issue) => (
      issue.code === "MODULE_BOUNDARY_DEFAULT_EXPORT"
      && issue.sourcePath === "src/build/content/docusaurus-preset-copy.ts"
    )));
    assert.equal(issues.some((issue) => (
      issue.code === "MODULE_BOUNDARY_DEFAULT_EXPORT"
      && issue.sourcePath === "src/build/content/docusaurus-preset.ts"
    )), false);
  });
});

