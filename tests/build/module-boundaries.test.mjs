function withFixture(callback) {
  const root = createFixture();
  try {
    callback(root);
  } finally {
    rmSync(root, {recursive: true, force: true});
  }
}

function issueCodes(root) {
  return checkModuleBoundaries({root}).issues.map((issue) => issue.code);
}

